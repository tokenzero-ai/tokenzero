// Bundles the stdio MCP server into one dependency-free file: mcp/bin/tokenzero-mcp.mjs.
// Shares the CLI's tokenizer swap (a character heuristic instead of js-tiktoken).
import { build } from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const outfile = process.argv[2] ?? path.join(here, 'bin', 'tokenzero-mcp.mjs');

await build({
  entryPoints: [path.join(here, 'src', 'main.ts')],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  banner: { js: '#!/usr/bin/env node\n// TokenZero MCP server (generated by mcp/build.mjs; do not edit)' },
  legalComments: 'none',
  logLevel: 'warning',
  plugins: [{
    name: 'lite-tokens',
    setup(b) {
      b.onResolve({ filter: /(^|\/)tokens\.ts$/ }, () => ({ path: path.join(here, '..', 'cli', 'src', 'tokens-lite.ts') }));
    },
  }],
});
