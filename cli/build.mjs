// Bundles the CLI into one dependency-free file: cli/bin/tokenzero.mjs.
// src/tokens.ts (js-tiktoken) is swapped for a character heuristic so the CLI
// stays small; the analyzer only uses counts as thresholds.
import { build } from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const outfile = process.argv[2] ?? path.join(here, 'bin', 'tokenzero.mjs');

await build({
  entryPoints: [path.join(here, 'src', 'main.ts')],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  banner: { js: '#!/usr/bin/env node\n// TokenZero CLI (generated by cli/build.mjs; do not edit)' },
  legalComments: 'none',
  logLevel: 'warning',
  plugins: [{
    name: 'lite-tokens',
    setup(b) {
      b.onResolve({ filter: /(^|\/)tokens\.ts$/ }, () => ({ path: path.join(here, 'src', 'tokens-lite.ts') }));
    },
  }],
});
